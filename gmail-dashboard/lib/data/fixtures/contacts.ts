function monthly(tones: Contact["toneHistory"][number]["tone"][]): Contact["toneHistory"] {
  const months = ["Apr", "May", "Jun", "Jul", "Aug", "Sep"];
  return months.map((month, i) => ({ month, tone: tones[i] ?? "neutral" }));
}

export function contactById(id: string): Contact {
  const c = CONTACTS.find((x) => x.id === id);
  if (!c) throw new Error(`Unknown contact: ${id}`);
  return c;
}
